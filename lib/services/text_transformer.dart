/// تحويلات عرض النصوص التجريبية في مُدَبِّر.
///
/// وضع المسند هنا هو تحويل حرفي بصري للأبجدية العربية إلى رموز
/// المسند (العربية الجنوبية القديمة). لا يغيّر نص حفص في قارئ QCF
/// الأساسي؛ يستخدم فقط في وضع العرض التجريبي للنصوص.
class TextTransformer {
  const TextTransformer._();

  static const Map<String, String> musnadMap = {
    'ا': '𐩱', 'أ': '𐩱', 'إ': '𐩱', 'آ': '𐩱', 'ٱ': '𐩱',
    'ب': '𐩨', 'ت': '𐩩', 'ث': '𐩻',
    'ج': '𐩴', 'ح': '𐩢', 'خ': '𐩭',
    'د': '𐩵', 'ذ': '𐩹', 'ر': '𐩧', 'ز': '𐩸',
    'س': '𐩪', 'ش': '𐩦', 'ص': '𐩮', 'ض': '𐩳',
    'ط': '𐩷', 'ظ': '𐩼', 'ع': '𐩲', 'غ': '𐩶',
    'ف': '𐩰', 'ق': '𐩤', 'ك': '𐩫', 'ل': '𐩡',
    'م': '𐩣', 'ن': '𐩬', 'ه': '𐩠', 'ة': '𐩠',
    'و': '𐩥', 'ي': '𐩺', 'ى': '𐩺', 'ؤ': '𐩥', 'ئ': '𐩺',
  };

  static const String _arabicMarks =
      '\\u064B\\u064C\\u064D\\u064E\\u064F\\u0650\\u0651\\u0652\\u0670';

  /// يستبدل الحروف العربية بحروف المسند المقابلة، مع إبقاء المسافات
  /// وعلامات الترقيم كما هي وإزالة التشكيل حتى لا تظهر علامات عربية
  /// فوق رموز المسند بشكل غير صحيح.
  static String toMusnad(String text) {
    final buffer = StringBuffer();
    for (final rune in text.runes) {
      final c = String.fromCharCode(rune);
      if (_arabicMarks.contains(c)) continue;
      buffer.write(musnadMap[c] ?? c);
    }
    return buffer.toString();
  }
}
